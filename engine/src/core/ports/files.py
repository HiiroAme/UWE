"""文件系统端口（P7）。

位置：
    引擎核心逻辑层 → ports 子包。

职责：
    定义"读一段文本、写一段文本、判断文件在不在、列出一个目录里的文件"这几件事的契约。
    真正碰磁盘的是适配器（例如 adapters.LocalFileSystem），核心只认这个抽象——
    换到网页版时换成另一个实现即可（§4 的端口与适配器原则）。

边界：
    - 本端口只管"文本"，不负责 JSON 解析、不负责版本校验（那是 core.persistence 的事）；
    - 不提供删除、移动、创建目录等能力：现在用不到（P8），需要时再加；
    - 列目录必须返回**确定顺序**（§13 确定性：不能依赖操作系统的枚举顺序）。

草案依据：
    §4 依赖方向（核心 → 端口接口 允许，核心 → 适配器实现 禁止）；
    §18.1 存档要落盘；P7 端口与适配器原则。
"""

from typing import Protocol


class FileSystem(Protocol):
    """文件读写端口。"""

    def exists(self, path: str) -> bool:
        """判断路径是否存在。

        输入：
            path: 文件路径（具体写法由适配器决定）。
        输出：
            True 表示能读到这个文件。
        """

    def read_text(self, path: str) -> str:
        """读取整个文件的内容。

        输入：
            path: 文件路径。
        输出：
            文件文本（编码由适配器决定）。
        异常：
            由适配器决定（通常是"文件不存在"或"读失败"）。
        """

    def write_text(self, path: str, text: str) -> None:
        """把一段文本写进文件（覆盖已有内容）。

        输入：
            path: 文件路径；
            text: 要写入的文本。
        输出：
            无。
            异常：
                由适配器决定（通常是"目录不存在"或"写失败"）。
        """

    def list_files(self, folder: str, suffix: str = "") -> tuple[str, ...]:
        """列出一个目录里的文件（不含子目录），按路径排序。

        输入：
            folder: 目录路径；
            suffix: 只保留以它结尾的文件（例如 ".json"）；空字符串表示全部。
        输出：
            文件路径元组，**按字符串排序**，保证同一份内容在任何机器上都按同样顺序读到。
        异常：
            由适配器决定（通常目录不存在时给空元组或报错，见实现说明）。
        """

    def list_dirs(self, folder: str) -> tuple[str, ...]:
        """列出一个目录下的子目录，按路径排序。

        输入：
            folder: 目录路径。
        输出：
            子目录路径元组（已排序）；目录不存在时给空元组。
        异常：
            由适配器决定。
        """
