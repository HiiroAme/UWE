"""引擎信息（名称 / 版本 / 演示标签的唯一来源）。

位置：
    引擎核心逻辑层。

职责：
    给出一个地方定义、到处引用的引擎名称与版本字符串：
        ENGINE_NAME：窗口标题、外壳首页标题用的项目名；
        ENGINE_VERSION：存档、日志、报错信息共用的运行版本；
        ENGINE_DEMO_LABEL / version_text()：游戏内左下角的版本角标（当前 demo 标签）。
    版本字符串的两个用途：
        1. 写进存档的"引擎版本"字段（§18.1），读档时用来判断兼容性；
        2. 写进日志与报错信息，便于用户报问题时说明"跑的是哪一版"。

版本号怎么升（约定，写在这里以免将来各写各的）：
    主.次.修订
        主：核心契约变化（存档结构、变化量字段、管线语义）；
        次：新增功能但不破坏已有契约（新增注册表、新增操作符）；
        修订：修 bug、补文档、纯内部重构。
    存档兼容只看三个"格式版本"（存档格式 / 变化量格式 / 条目 schema），
    它们各自在自己的模块里定义；本常量只是给人看的运行版本。

草案依据：
    §18.1 存档结构的第一项就是"引擎版本"；D-25 版本不匹配直接报错拒绝加载。
"""

# 引擎名：窗口标题、外壳默认标题、首页大标题共用同一份（不要在 UI 里再抄字符串）。
ENGINE_NAME = "通用兵棋引擎(UWE)"

# 引擎运行版本。改动契约时记得同步升这里与相应的格式版本。
# 未发布期一律 0.0.0（0.x 表示"还没定型"，见 plans/新架构细节/01_实施依据/模块与Mod格式.md §0.2）。
ENGINE_VERSION = "0.0.0"

# 游戏内版本角标的后缀：目前是可行性 demo；以后正式版改这里即可。
ENGINE_DEMO_LABEL = "demo"


def version_text() -> str:
    """游戏内左下角显示的版本文字：version:<版本>(<演示标签>)。"""
    return f"version:{ENGINE_VERSION}({ENGINE_DEMO_LABEL})"
